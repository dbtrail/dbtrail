// OutputFormatPsql writes each table of a full-table reconstruct of a
// PostgreSQL source as one SQL file psql loads (#1596 slice 2): the table's
// CREATE TABLE, built from the snapshot's recorded shape, then its rows as a
// COPY ... FROM stdin block, in one transaction.
const OutputFormatPsql = "psql"

// pgQuoteIdent quotes a PostgreSQL identifier, always: a name is stored
// case-sensitively, so a bare one would be folded to lower case.
func pgQuoteIdent(s string) string { return `"` + strings.ReplaceAll(s, `"`, `""`) + `"` }

// pgQuoteLiteral quotes a string literal. standard_conforming_strings is on
// in every supported PostgreSQL, so a backslash is an ordinary character.
func pgQuoteLiteral(s string) string { return "'" + strings.ReplaceAll(s, "'", "''") + "'" }

// pgCopyEscaper escapes a value for COPY's text format.
var pgCopyEscaper = strings.NewReplacer(`\`, `\\`, "\n", `\n`, "\r", `\r`, "\t", `\t`)

// pgCopyValue is one field of a COPY text row: \N for NULL, else the value,
// escaped. A value is PostgreSQL's own text (the snapshot's, or a change's);
// anything else would load as something else, so it is refused.
func pgCopyValue(v any, column string) (string, error) {
	switch s := v.(type) {
	case nil:
		return `\N`, nil
	case string:
		return pgCopyEscaper.Replace(s), nil
	}
	return "", fmt.Errorf("column %q holds a %T, not PostgreSQL text; it cannot be written as it would load", column, v)
}

// pgLoadSettings is the SET statements a load runs before the rows: the
// settings the values were rendered under (baseline.MetaKeyRenderGUCs, as
// k=v;...), which the parsing side must share, and UTF-8.
func pgLoadSettings(gucs string) (string, error) {
	var b strings.Builder
	b.WriteString("SET client_encoding = 'UTF8';\n")
	for f := range strings.SplitSeq(gucs, ";") {
		if f == "" {
			continue
		}
		k, v, ok := strings.Cut(f, "=")
		if !ok || k == "" {
			return "", fmt.Errorf("the snapshot's rendering settings %q cannot be read", gucs)
		}
		fmt.Fprintf(&b, "SET %s = %s;\n", k, pgQuoteLiteral(v))
	}
	return b.String(), nil
}

// pgCreateTable is the DDL that makes schema.table as the snapshot recorded
// it: the schema, the sequences serial columns own, the columns in table
// order (generated ones in place, with their expressions), NOT NULL,
// defaults, identity, and the primary key. Not recorded, so not made:
// indexes other than the key, other constraints, collations, comments,
// grants, and any type or sequence a default refers to that the table does
// not own. A shape recorded before these facts were (no column has an
// ordinal) is refused.
func pgCreateTable(schema, table string, rel baseline.PGRelation) (string, error) {
	name := pgQuoteIdent(schema) + "." + pgQuoteIdent(table)
	type line struct {
		ord  int
		text string
	}
	var lines []line
	var serials []baseline.PGColumn
	for _, c := range rel.Columns {
		if c.Ordinal == 0 {
			return "", fmt.Errorf("%s.%s: the snapshot does not record what its CREATE TABLE needs (it was taken by a version before this one); %s",
				schema, table, pgRebaseline)
		}
		if c.Type == "" {
			return "", fmt.Errorf("%s.%s: the snapshot does not record the type of column %q; %s", schema, table, c.Name, pgRebaseline)
		}
		if c.Sequence != "" && c.Seq == (baseline.PGSequence{}) {
			return "", fmt.Errorf("%s.%s: the snapshot does not record the options of the sequence column %q owns; %s", schema, table, c.Name, pgRebaseline)
		}
		l := pgQuoteIdent(c.Name) + " " + c.Type
		switch c.Identity {
		case "a":
			l += " GENERATED ALWAYS AS IDENTITY (" + pgSequenceOptions(c.Seq) + ")"
		case "d":
			l += " GENERATED BY DEFAULT AS IDENTITY (" + pgSequenceOptions(c.Seq) + ")"
		default:
			if c.Default != "" {
				l += " DEFAULT " + c.Default
			}
			if c.Sequence != "" {
				serials = append(serials, c)
			}
		}
		if c.NotNull {
			l += " NOT NULL"
		}
		lines = append(lines, line{c.Ordinal, l})
	}
	for _, g := range rel.Generated {
		kind := " STORED"
		if g.Virtual {
			kind = " VIRTUAL"
		}
		l := pgQuoteIdent(g.Name) + " " + g.Type + " GENERATED ALWAYS AS (" + g.Expr + ")" + kind
		if g.NotNull {
			l += " NOT NULL"
		}
		lines = append(lines, line{g.Ordinal, l})
	}
	slices.SortStableFunc(lines, func(a, b line) int { return a.ord - b.ord })

	var b strings.Builder
	fmt.Fprintf(&b, "CREATE SCHEMA IF NOT EXISTS %s;\n", pgQuoteIdent(schema))
	// Never IF NOT EXISTS: a sequence of that name left by the table being
	// recovered (renamed aside) would be taken over, and moved back.
	for _, c := range serials {
		fmt.Fprintf(&b, "CREATE SEQUENCE %s AS %s %s;\n", c.Sequence, c.Seq.Type, pgSequenceOptions(c.Seq))
	}
	fmt.Fprintf(&b, "CREATE TABLE %s (\n", name)
	for i, l := range lines {
		b.WriteString("  " + l.text)
		if i < len(lines)-1 || len(rel.PrimaryKey) > 0 {
			b.WriteString(",")
		}
		b.WriteString("\n")
	}
	if len(rel.PrimaryKey) > 0 {
		key := make([]string, len(rel.PrimaryKey))
		for i, k := range rel.PrimaryKey {
			key[i] = pgQuoteIdent(k)
		}
		fmt.Fprintf(&b, "  PRIMARY KEY (%s)\n", strings.Join(key, ", "))
	}
	b.WriteString(");\n")
	for _, c := range serials {
		fmt.Fprintf(&b, "ALTER SEQUENCE %s OWNED BY %s.%s;\n", c.Sequence, name, pgQuoteIdent(c.Name))
	}
	return b.String(), nil
}

// pgSequenceOptions spells a sequence's recorded options (not its type: an
// identity column's sequence takes the column's).
func pgSequenceOptions(q baseline.PGSequence) string {
	cycle := "NO CYCLE"
	if q.Cycle {
		cycle = "CYCLE"
	}
	return fmt.Sprintf("INCREMENT BY %d MINVALUE %d MAXVALUE %d START WITH %d CACHE %d %s", q.Increment, q.Min, q.Max, q.Start, q.Cache, cycle)
}

// pgSetSequences moves every sequence a column owns (serial or identity)
// past the loaded rows, so the next insert does not collide with one: past
// the highest, or for a descending sequence the lowest; with no row, to its
// start. The sequence's own position at the point is not recorded: this is
// the nearest safe value.
func pgSetSequences(schema, table string, rel baseline.PGRelation) string {
	name := pgQuoteIdent(schema) + "." + pgQuoteIdent(table)
	var b strings.Builder
	for _, c := range rel.Columns {
		if c.Sequence == "" {
			continue
		}
		col := pgQuoteIdent(c.Name)
		agg := "MAX"
		if c.Seq.Increment < 0 {
			agg = "MIN"
		}
		start := c.Seq.Start
		if start == 0 && c.Seq == (baseline.PGSequence{}) {
			start = 1
		}
		fmt.Fprintf(&b, "SELECT setval(pg_get_serial_sequence(%s, %s), COALESCE(%s(%s), %d), %s(%s) IS NOT NULL) FROM %s;\n",
			pgQuoteLiteral(name), pgQuoteLiteral(c.Name), agg, col, start, agg, col, name)
	}
	return b.String()
}

// pgFileName is the file a table's SQL goes to: <schema>.<table>.sql, with
// the characters a file name cannot hold, the dot that separates the two
// names, and control characters percent-escaped (a PostgreSQL name can hold
// any of them), so two tables never share a name. Case is kept: see
// pgFileCollisions.
func pgFileName(schema, table string) string {
	esc := func(s string) string {
		var b strings.Builder
		for _, r := range s {
			if r == '%' || r == '/' || r == '.' || r == '\\' || r < 0x20 || r == 0x7f {
				fmt.Fprintf(&b, "%%%02X", r)
				continue
			}
			b.WriteRune(r)
		}
		return b.String()
	}
	return esc(schema) + "." + esc(table) + ".sql"
}

// pgFileCollisions refuses a run whose tables would share a file on a disk
// that does not tell case apart (macOS, Windows): one would replace the
// other, and the run would publish as complete without it.
func pgFileCollisions(tables []string) error {
	seen := map[string]string{}
	for _, e := range tables {
		schema, table, ok := splitSchemaTable(e)
		if !ok {
			continue
		}
		f := pgFileName(schema, table)
		k := strings.ToLower(f)
		if prev, dup := seen[k]; dup {
			return fmt.Errorf("%s and %s would be written to one file (%s) on a disk that does not tell case apart; reconstruct them in separate runs, to separate output directories", prev, e, f)
		}
		seen[k] = e
	}
	return nil
}

// pgCommentText is s with every control character replaced, for a comment
// line: a newline in a name would end the comment and make the rest SQL.
func pgCommentText(s string) string {
	return strings.Map(func(r rune) rune {
		if r < 0x20 || r == 0x7f {
			return '?'
		}
		return r
	}, s)
}

// mergeBaselineIntoPsql writes the table as one SQL file psql loads: in one
// transaction, the settings the values were rendered under, the CREATE
// TABLE, the rows as COPY ... FROM stdin, and the sequences moved past them.
// Written to a temporary name and renamed when complete, so a failed table
// leaves no file that loads part of it.
func mergeBaselineIntoPsql(ctx context.Context, in mergeInput, rep *TableReport) (retErr error) {
	colNames, err := prepareMerge(ctx, in)
	if err != nil {
		return err
	}
	rel, _, err := baseline.ParsePGRelation(in.SourceBaseline.Metadata.PGRelation)
	if err != nil {
		return fmt.Errorf("%s.%s: read the snapshot's recorded table shape: %w", in.Schema, in.Table, err)
	}
	if err := checkPGFileColumns(rel, colNames, in.Schema, in.Table); err != nil {
		return err
	}
	create, err := pgCreateTable(in.Schema, in.Table, rel)
	if err != nil {
		return err
	}
	settings, err := pgLoadSettings(in.SourceBaseline.Metadata.RenderGUCs)
	if err != nil {
		return fmt.Errorf("%s.%s: %w", in.Schema, in.Table, err)
	}
	name := pgQuoteIdent(in.Schema) + "." + pgQuoteIdent(in.Table)
	quoted := make([]string, len(colNames))
	for i, c := range colNames {
		quoted[i] = pgQuoteIdent(c)
	}

	file := pgFileName(in.Schema, in.Table)
	path := filepath.Join(in.OutputDir, file)
	f, err := os.CreateTemp(in.OutputDir, "."+file+".*")
	if err != nil {
		return fmt.Errorf("create the SQL file for %s.%s: %w", in.Schema, in.Table, err)
	}
	defer func() {
		if retErr != nil {
			f.Close()
			os.Remove(f.Name())
		}
	}()
	w := newOffsetWriter(f, 1<<20)
	offset := w.Offset
	fmt.Fprintf(w, "-- %s as of %s, rebuilt by bintrail from the snapshot of %s and the changes after it.\n",
		pgCommentText(name), in.SnapshotAt.UTC().Format(time.RFC3339), in.SourceBaseline.Time.UTC().Format(time.RFC3339))
	fmt.Fprintf(w, "-- Load with: psql -v ON_ERROR_STOP=1 -f '%s'\n", pgCommentText(strings.ReplaceAll(file, "'", `'\''`)))
	w.WriteString("-- Made from the snapshot's recorded shape: columns, types, NOT NULL, defaults, identity and sequences, generated columns, the primary key.\n" +
		"-- Not made: other indexes and constraints, partitioning (a partition is made as a table of its own), collations, comments, grants,\n" +
		"-- and types or sequences a default refers to. A money value is read under the loading server's lc_monetary.\n")
	w.WriteString("BEGIN;\n")
	w.WriteString(settings)
	w.WriteString(create)
	copyStmt := fmt.Sprintf("COPY %s (%s) FROM stdin", name, strings.Join(quoted, ", "))
	w.WriteString(copyStmt + ";\n")
	dataStart := offset()

	fields := make([]string, len(colNames))
	var written int64
	stats, err := mergeBaselineImages(ctx, mergeCore{
		LocalBaselinePath: in.LocalBaselinePath,
		Schema:            in.Schema,
		Table:             in.Table,
		PKCols:            in.PKCols,
		Changes:           in.Changes,
		Spill:             in.Spill,
		PGTextPK:          true,
		CheckPass: func(m map[string]*query.ResultRow) error {
			return checkPostBaselineColumns(in, m, colNames)
		},
		DuckDBTuning: in.DuckDBTuning,
	}, func(row map[string]any) error {
		for i, c := range colNames {
			v, err := pgCopyValue(row[c], c)
			if err != nil {
				return fmt.Errorf("%s.%s: %w", in.Schema, in.Table, err)
			}
			fields[i] = v
		}
		written++
		_, err := w.WriteString(strings.Join(fields, "\t") + "\n")
		return err
	})
	if err != nil {
		return err
	}
	dataEnd := offset()
	w.WriteString("\\.\n")
	w.WriteString(pgSetSequences(in.Schema, in.Table, rel))
	w.WriteString("COMMIT;\n")
	if err := w.Flush(); err != nil {
		return fmt.Errorf("write the SQL file for %s.%s: %w", in.Schema, in.Table, err)
	}
	if err := f.Sync(); err != nil {
		return fmt.Errorf("write the SQL file for %s.%s: %w", in.Schema, in.Table, err)
	}
	if err := f.Close(); err != nil {
		return fmt.Errorf("write the SQL file for %s.%s: %w", in.Schema, in.Table, err)
	}
	if err := os.Rename(f.Name(), path); err != nil {
		os.Remove(f.Name())
		return fmt.Errorf("publish the SQL file for %s.%s: %w", in.Schema, in.Table, err)
	}
	rep.BaselineRows = stats.BaselineRows
	rep.UpdatesApplied = stats.UpdatesApplied
	rep.InsertsEmitted = stats.InsertsEmitted
	rep.DeletesSkipped = stats.DeletesSkipped
	rep.RowsWritten = written
	rep.Files = []string{file}
	rep.PsqlCopy = &PsqlCopy{Statement: copyStmt, DataStart: dataStart, DataEnd: dataEnd}
	return nil
}

// PsqlCopy is where a psql output file's COPY sits: Statement is the COPY
// (without its semicolon), and the bytes [DataStart, DataEnd) are its rows,
// ending in a newline unless there are none. Before DataStart is the SQL that
// runs ahead of it, ending in the statement's own line; from DataEnd come the
// end-of-data line `\.` and the SQL that runs after. Found by position, not by
// reading the file: a default's text can hold a line that looks like either.
type PsqlCopy struct {
	Statement          string
	DataStart, DataEnd int64
}

// offsetWriter is a buffered writer that knows how many bytes it has been
// given: those already passed down plus those still buffered.
type offsetWriter struct {
	*bufio.Writer
	counted *countingWriter
}

func newOffsetWriter(w io.Writer, size int) offsetWriter {
	c := &countingWriter{w: w}
	return offsetWriter{Writer: bufio.NewWriterSize(c, size), counted: c}
}

func (o offsetWriter) Offset() int64 { return o.counted.n + int64(o.Buffered()) }

type countingWriter struct {
	w io.Writer
	n int64
}

func (c *countingWriter) Write(p []byte) (int, error) {
	n, err := c.w.Write(p)
	c.n += int64(n)
	return n, err
}
