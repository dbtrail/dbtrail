// The psql-loadable output (#1596 slice 2) is built from the snapshot's
// recorded shape. Every case here is a way the generated text could load into
// a table that is not the source's, or not load at all.

func TestPGQuoteIdent(t *testing.T) {
	for in, want := range map[string]string{
		"orders": `"orders"`, "Facts Tbl": `"Facts Tbl"`, `we"ird`: `"we""ird"`, "año": `"año"`, "": `""`,
	} {
		if got := pgQuoteIdent(in); got != want {
			t.Errorf("pgQuoteIdent(%q) = %s, want %s", in, got, want)
		}
	}
	if got := pgQuoteLiteral(`it's \ "x"`); got != `'it''s \ "x"'` {
		t.Errorf("pgQuoteLiteral = %s", got)
	}
}

// COPY text format: backslash, newline, carriage return and tab are escaped;
// NULL is \N, distinct from an empty string and from the two characters \N.
func TestPGCopyValue(t *testing.T) {
	for _, c := range []struct {
		in   any
		want string
	}{
		{nil, `\N`},
		{"", ""},
		{`\N`, `\\N`},
		{"tab\there\nnew\rline\\back", `tab\there\nnew\rline\\back`},
		{`\x00ff`, `\\x00ff`},
		{"café 日本語", "café 日本語"},
	} {
		got, err := pgCopyValue(c.in, "c")
		if err != nil || got != c.want {
			t.Errorf("pgCopyValue(%q) = %q, %v; want %q", c.in, got, err, c.want)
		}
	}
	// A value that is not PostgreSQL's own text would load as something
	// else: refused, never formatted.
	for _, bad := range []any{float64(1), true, map[string]any{}} {
		if _, err := pgCopyValue(bad, "c"); err == nil || !strings.Contains(err.Error(), `column "c"`) {
			t.Errorf("pgCopyValue(%#v) = %v, want a refusal naming the column", bad, err)
		}
	}
}

var facts = baseline.PGRelation{OID: 16500,
	Columns: []baseline.PGColumn{
		{Name: "id", TypeOID: 23, TypeMod: -1, Type: "integer", NotNull: true, Default: `nextval('"Facts Tbl_id_seq"'::regclass)`, Sequence: `public."Facts Tbl_id_seq"`, Ordinal: 1, Seq: baseline.PGSequence{Type: "integer", Start: 1, Increment: 1, Min: 1, Max: 2147483647, Cache: 1}},
		{Name: "tenant", TypeOID: 23, TypeMod: -1, Type: "integer", NotNull: true, Identity: "d", Sequence: `public."Facts Tbl_tenant_seq"`, Ordinal: 2, Seq: baseline.PGSequence{Type: "integer", Start: 1, Increment: 1, Min: 1, Max: 2147483647, Cache: 1}},
		{Name: "note", TypeOID: 25, TypeMod: -1, Type: "text", NotNull: true, Default: "'it''s'::text", Ordinal: 4},
		{Name: "v", TypeOID: 1043, TypeMod: 24, Type: "character varying(20)", Ordinal: 5},
		{Name: "always", TypeOID: 20, TypeMod: -1, Type: "bigint", NotNull: true, Identity: "a", Sequence: `public."Facts Tbl_always_seq"`, Ordinal: 6,
			Seq: baseline.PGSequence{Type: "bigint", Start: -1, Increment: -1, Min: -100, Max: -1, Cache: 1, Cycle: true}},
	},
	PrimaryKey: []string{"tenant", "id"},
	Generated:  []baseline.PGGeneratedColumn{{Name: "twice", Type: "integer", Expr: "(id * 2)", Ordinal: 3}},
}

func TestPGCreateTable(t *testing.T) {
	got, err := pgCreateTable("public", "Facts Tbl", facts)
	if err != nil {
		t.Fatal(err)
	}
	t.Logf("\n%s", got)
	want := `CREATE SCHEMA IF NOT EXISTS "public";
CREATE SEQUENCE public."Facts Tbl_id_seq" AS integer INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START WITH 1 CACHE 1 NO CYCLE;
CREATE TABLE "public"."Facts Tbl" (
  "id" integer DEFAULT nextval('"Facts Tbl_id_seq"'::regclass) NOT NULL,
  "tenant" integer GENERATED BY DEFAULT AS IDENTITY (INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START WITH 1 CACHE 1 NO CYCLE) NOT NULL,
  "twice" integer GENERATED ALWAYS AS ((id * 2)) STORED,
  "note" text DEFAULT 'it''s'::text NOT NULL,
  "v" character varying(20),
  "always" bigint GENERATED ALWAYS AS IDENTITY (INCREMENT BY -1 MINVALUE -100 MAXVALUE -1 START WITH -1 CACHE 1 CYCLE) NOT NULL,
  PRIMARY KEY ("tenant", "id")
);
ALTER SEQUENCE public."Facts Tbl_id_seq" OWNED BY "public"."Facts Tbl"."id";
`
	if got != want {
		t.Fatalf("got:\n%s\nwant:\n%s", got, want)
	}
}

// The sequences are moved past the loaded rows, or the next insert collides
// with one of them.
func TestPGSetSequences(t *testing.T) {
	got := pgSetSequences("public", "Facts Tbl", facts)
	for _, want := range []string{
		`SELECT setval(pg_get_serial_sequence('"public"."Facts Tbl"', 'id'), COALESCE(MAX("id"), 1), MAX("id") IS NOT NULL) FROM "public"."Facts Tbl";`,
		`SELECT setval(pg_get_serial_sequence('"public"."Facts Tbl"', 'tenant'), COALESCE(MAX("tenant"), 1), MAX("tenant") IS NOT NULL) FROM "public"."Facts Tbl";`,
		// A descending sequence goes past the lowest row, and starts from
		// its own start when there is none.
		`SELECT setval(pg_get_serial_sequence('"public"."Facts Tbl"', 'always'), COALESCE(MIN("always"), -1), MIN("always") IS NOT NULL) FROM "public"."Facts Tbl";`,
	} {
		if !strings.Contains(got, want) {
			t.Errorf("missing %s in:\n%s", want, got)
		}
	}
	if strings.Contains(got, `'note'`) || strings.Contains(got, `'v'`) {
		t.Errorf("a column with no sequence is set:\n%s", got)
	}
}

// A snapshot that did not record the facts cannot produce a CREATE TABLE
// that matches its source: refused with the remedy, never guessed.
func TestPGCreateTable_refusesAShapeWithoutFacts(t *testing.T) {
	old := baseline.PGRelation{OID: 7, Columns: []baseline.PGColumn{{Name: "id", TypeOID: 23, TypeMod: -1, Type: "integer"}}}
	if _, err := pgCreateTable("public", "t", old); err == nil || !strings.Contains(err.Error(), "bintrail-pg baseline") {
		t.Fatalf("err = %v, want the refusal naming a new snapshot", err)
	}
	noType := baseline.PGRelation{OID: 7, Columns: []baseline.PGColumn{{Name: "id", TypeOID: 23, TypeMod: -1, Ordinal: 1}}}
	if _, err := pgCreateTable("public", "t", noType); err == nil {
		t.Fatal("a column with no type spelling was accepted")
	}
}

// The values were rendered under the snapshot's pinned settings; the load
// parses them under the same ones.
func TestPGLoadSettings(t *testing.T) {
	got, err := pgLoadSettings(baseline.RenderGUCsPinned)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"SET TimeZone = 'UTC';", "SET DateStyle = 'ISO';", "SET IntervalStyle = 'postgres';", "SET client_encoding = 'UTF8';"} {
		if !strings.Contains(got, want) {
			t.Errorf("missing %s in:\n%s", want, got)
		}
	}
	if _, err := pgLoadSettings("TimeZone=UTC;=ISO"); err == nil {
		t.Error("an unreadable setting list was accepted")
	}
}

// A sequence or identity column whose options the snapshot did not record
// would be made with other ones (a descending one ascending): refused.
func TestPGCreateTable_refusesASequenceWithoutOptions(t *testing.T) {
	rel := baseline.PGRelation{OID: 7, Columns: []baseline.PGColumn{{Name: "id", TypeOID: 23, TypeMod: -1, Type: "integer", Identity: "a", Sequence: "public.t_id_seq", Ordinal: 1}}}
	if _, err := pgCreateTable("public", "t", rel); err == nil || !strings.Contains(err.Error(), "sequence") {
		t.Fatalf("err = %v", err)
	}
}

// A PostgreSQL 18 VIRTUAL generated column is made VIRTUAL.
func TestPGCreateTable_virtualGenerated(t *testing.T) {
	rel := baseline.PGRelation{OID: 7, Columns: []baseline.PGColumn{{Name: "id", TypeOID: 23, TypeMod: -1, Type: "integer", Ordinal: 1}},
		Generated: []baseline.PGGeneratedColumn{{Name: "v", Type: "integer", Expr: "(id + 1)", Ordinal: 2, Virtual: true}}}
	got, err := pgCreateTable("public", "t", rel)
	if err != nil || !strings.Contains(got, `"v" integer GENERATED ALWAYS AS ((id + 1)) VIRTUAL`) {
		t.Fatalf("got %s, %v", got, err)
	}
}

// A name is never written raw outside a quoted identifier: a newline in a
// table name would end a comment line and make the rest SQL.
func TestPGCommentText(t *testing.T) {
	if got := pgCommentText("x\nDROP TABLE accounts; --\r\x00"); strings.ContainsAny(got, "\n\r\x00") {
		t.Fatalf("pgCommentText = %q", got)
	}
}

// One file per table, never two tables in one: dots are escaped apart, so
// a.b + c and a + b.c cannot meet. A run whose tables differ only in case is
// refused, since a disk that folds case would put both in one file.
func TestPGFileName(t *testing.T) {
	names := map[string]bool{}
	for _, st := range [][2]string{{"a.b", "c"}, {"a", "b.c"}, {"pub/lic", "x"}, {"pub%2Flic", "x"}, {"public", "Orders"}} {
		n := pgFileName(st[0], st[1])
		if strings.Contains(n, "/") || names[n] {
			t.Fatalf("pgFileName(%q, %q) = %q, collides or holds a slash (%v)", st[0], st[1], n, names)
		}
		names[n] = true
	}
	if got := pgFileName("public", "orders"); got != "public.orders.sql" {
		t.Errorf("a plain name = %q", got)
	}
	if err := pgFileCollisions([]string{"public.Orders", "public.orders"}); err == nil || !strings.Contains(err.Error(), "public.Orders") {
		t.Errorf("a case collision: %v", err)
	}
	if err := pgFileCollisions([]string{"public.a", "public.b"}); err != nil {
		t.Errorf("distinct names: %v", err)
	}
}
