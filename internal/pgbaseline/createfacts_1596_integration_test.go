// The snapshot records what a CREATE TABLE needs beyond the column list
// (#1596 slice 2), read from the catalog in the snapshot's transaction: NOT
// NULL, defaults, identity and the sequences columns own, the generated
// columns with their expressions and positions, and the primary key in key
// order (not table order), for a name that needs quoting.
func TestPGBaseline_RecordsCreateTableFacts(t *testing.T) {
	baseDSN := testutil.SkipIfNoPostgres(t)
	ctx := context.Background()
	const pub, slot, tbl = "pgbaseline_facts_pub", "pgbaseline_facts_slot", `"Facts Tbl"`
	setup, err := pgx.Connect(ctx, baseDSN)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { setup.Close(context.Background()) })
	dropAll := func() {
		bg := context.Background()
		_, _ = setup.Exec(bg, "DROP PUBLICATION IF EXISTS "+pub)
		_, _ = setup.Exec(bg, "DROP TABLE IF EXISTS "+tbl)
		_, _ = setup.Exec(bg, "SELECT pg_drop_replication_slot($1) WHERE EXISTS (SELECT 1 FROM pg_replication_slots WHERE slot_name=$1)", slot)
	}
	dropAll()
	t.Cleanup(dropAll)
	for _, q := range []string{
		`CREATE TABLE ` + tbl + ` (
			id serial,
			tenant int GENERATED BY DEFAULT AS IDENTITY,
			twice int GENERATED ALWAYS AS (id * 2) STORED,
			note text NOT NULL DEFAULT 'it''s',
			v varchar(20),
			PRIMARY KEY (tenant, id))`,
		`INSERT INTO ` + tbl + ` (note) VALUES ('x')`,
		fmt.Sprintf("CREATE PUBLICATION %s FOR TABLE %s", pub, tbl),
	} {
		if _, err := setup.Exec(ctx, q); err != nil {
			t.Fatalf("%s: %v", q, err)
		}
	}
	out := t.TempDir()
	_, err = pgbaseline.Run(ctx, pgbaseline.Config{
		QueryDSN: baseDSN, ReplDSN: replDSN(baseDSN), SlotName: slot, Publication: pub,
		OutputDir: out, Compression: "zstd", Parallelism: 1,
	})
	if err != nil {
		t.Fatalf("pgbaseline.Run: %v", err)
	}
	md := readParquetMetadata(t, filepath.Join(singleSnapshotDir(t, out), "public", "Facts Tbl.parquet"))
	rel, ok, err := baseline.ParsePGRelation(md[baseline.MetaKeyPGRelation])
	if err != nil || !ok {
		t.Fatalf("shape %q: %v %v", md[baseline.MetaKeyPGRelation], ok, err)
	}
	want := []baseline.PGColumn{
		{Name: "id", TypeOID: 23, TypeMod: -1, Type: "integer", NotNull: true, Default: `nextval('"Facts Tbl_id_seq"'::regclass)`, Sequence: `public."Facts Tbl_id_seq"`, Ordinal: 1},
		{Name: "tenant", TypeOID: 23, TypeMod: -1, Type: "integer", NotNull: true, Identity: "d", Sequence: `public."Facts Tbl_tenant_seq"`, Ordinal: 2},
		{Name: "note", TypeOID: 25, TypeMod: -1, Type: "text", NotNull: true, Default: "'it''s'::text", Ordinal: 4},
		{Name: "v", TypeOID: 1043, TypeMod: 24, Type: "character varying(20)", Ordinal: 5},
	}
	if len(rel.Columns) != len(want) {
		t.Fatalf("columns = %+v", rel.Columns)
	}
	for i := range want {
		if rel.Columns[i] != want[i] {
			t.Errorf("column %d = %+v, want %+v", i, rel.Columns[i], want[i])
		}
	}
	if len(rel.PrimaryKey) != 2 || rel.PrimaryKey[0] != "tenant" || rel.PrimaryKey[1] != "id" {
		t.Errorf("primary key = %v, want [tenant id]", rel.PrimaryKey)
	}
	if len(rel.Generated) != 1 || rel.Generated[0] != (baseline.PGGeneratedColumn{Name: "twice", Type: "integer", Expr: "(id * 2)", Ordinal: 3}) {
		t.Errorf("generated = %+v", rel.Generated)
	}
}
