package settings

// The words for every operator setting (#2671): what it changes, its default,
// a value to write, and which programs read it. Everything a person reads
// about a setting is generated from this: the commented option file the
// packages ship (build/packaging/bintrail-console/dbtrail.cnf) and the page of
// every option (docs/option-reference.md). TestEveryOperatorSettingHasDocs
// keeps it equal to the table; TestGeneratedFilesAreCurrent keeps the two
// files equal to it.
//
// Texts name other settings by their variable (BINTRAIL_SSL_CERT); the option
// file writes them by their option name (ssl-cert).

// Group is a heading of the option file and of the page.
type Group struct {
	ID    string
	Title string
}

